/// 上限。`Exprs` と `Bound` の両方 が引く。
module FsBulletML2.Generate.Consts

/// AST の `fire` 要素 の数。撃った弾 の数 ではない
let [<Literal>] MAX_FIRES = 400

/// 同時 に画面 に居る 弾 の上限。`Generate` が組んだ 木 についての 約束 で、
/// `Edit`（段・仕掛け・混ぜ・散らし）を通した あと は 誰 も 約束 して いない。
///
/// 素 の生成 は ほぼ 守る —— 14 軸 を振った 120 通り を 300 コマ 走らせて
/// 900 超え は 4 本、最大 1,080 発、実測/上界 は 最大 1.72・中央 0.72。
///
/// 越える のは `Edit` の層。`Tune.applySteps` の `split` は 葉 を 4 発 に割って
/// 親 を消す ので 1 段 で 約 4 倍 になる（収録 4 本 の実測 2.6〜4.1 倍）。
/// 面 を通した 天井 が要る 側 は、そちら で 別 に数 を置く
let [<Literal>] MAX_ALIVE = 900

/// 弾速 の上限。`$rank = 1.0` で見る
let [<Literal>] MAX_SPEED = 6.0

/// `repeat` の `times` の上限。`$rank = 1.0` で見る
let [<Literal>] MAX_REPEAT = 200

/// 弾 が生きて いる コマ数 の上限。生成器 の `wait "180"` に合わせる
let [<Literal>] BULLET_LIFE = 180.0

/// 弾 が画面 を抜ける まで に進む 距離。面 は 480x640 で、撃つ のは 中ほど から ——
/// 端 まで 240〜320 なので その間 を取る。
///
/// 速い 弾 は `BULLET_LIFE` より 先 に 画面 から 出る。見ない と 上界 が
/// 3 倍 過大 になり、`fit` が `wait` を 7 倍 に伸ばして
/// 「速いが スカスカ」な弾幕 が出る（実機 で踏んだ）
let [<Literal>] FIELD_SPAN = 280.0
