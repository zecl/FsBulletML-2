namespace FsBulletML2

/// 走行の記録の受け口。**既定は `ignore`。何も繋がなければ何もしない。**
///
/// v2.9 で 4 通り の形を測って、この形に決めた
/// （`src/FsBulletML2.Playground/README.md` の「線を越える」）——
///
///     Env に口を足す        OFF が素に戻らない（5way で +1.92%）
///     int を走査で運ぶ      費用が inline の判断に乗るので表にできない
///     module の可変な口     OFF が素に戻る。**これ**
///
/// **番号は持たない。** いちど「`Progress` の腕に番号（`int`）を足す」形で
/// 決めたが、当てる先を開いたら `Progress` は 3 通り の歩き方
/// （`Progress.initial` / `Step.rootProgress` / `Step.resetChild`）で、しかも
/// **子の並びの途中から組み直される**（`Step.action` の展開、`repeat` の次周、
/// 撃たれた弾の tops）。**組む順の連番では、そこで振り直せない。**
///
/// 代わりに**台本のノードそのもの**を渡す。ノードは参照型で、同じ台本の同じ
/// 要素は弾をまたいで同じ物なので、**受け取る側が参照を鍵にした表を持てる。**
/// これで `Progress` を 1 行 も触らずに済み、測ってあった番号の費用
/// （8 バイト x 腕の個数、224 本 の最悪 1.40%）も払わない。
///
/// **グローバルな可変。** 面を 2 枚 並べても、2 面 は同じコマの中で順に進み
/// （`Main.fs` の `tick`）、wasm はスレッドが 1 本 しか無いので、
/// **呼ぶ側が面ごと・弾ごとに付け替えれば分けられる。**
/// 付け替える責任は呼ぶ側に在る —— ここは口を開けるだけ。
module NodeTrace =

  /// そのコマに**通った**ノード。`Step.command` と `Step.actionElm` の入口。
  ///
  /// 渡すのは `Action` か `ActionElm`。**型が 2 つ あるので `obj`** ——
  /// 受け取る側は参照を鍵に使うだけなので、型で分ける利がない。
  let mutable visit : obj -> unit = ignore

  /// そのコマに**止まった**ノード ＝ 次のコマの再開点。
  ///
  /// **`visit` の部分集合ではない使い方をする。** v3.1 が字の上で光らせるのは
  /// こちら（`visit` は同梱 224 本 で 1 コマ 最大 200 か所、こちらは最大 101）。
  let mutable stop : obj -> unit = ignore

/// 組む段が作ったノードと、その元のノードの対。**既定は繋がない。**
///
/// 段 1 の受け口が渡すのは**走る木のノード**だが、字に結べるのは
/// **読んだ木のノード**。組む段は 2 手 で新しい木を作り、**参照を 1 件 も
/// 保たない**（同梱 176 本 で測った。README の「段 2 の当てる先」）——
///
///     畳み   foldConstants。腕は動かないので歩く順で結べる（176 / 176）
///     展開   convertRefActionElm。歩く順では結べない（42.09%）
///
/// 保たれて見えた 265 件 と 17 件 は**全部 vanish** で、引数なしの腕が
/// singleton だから同じ物が返っていただけ。**だから対でしまう。**
///
/// **`enabled` が別に在るのは、歩く費用が木の大きさに比例するから。**
/// 段 1 の受け口は「呼ぶだけ」なので既定 `ignore` で足りたが、こちらは
/// 畳みの対を作るのに木を 1 周 する。**繋がないときは歩かない。**
module NodeOrigin =

  /// 対を作るか。**既定は false。歩きそのものを飛ばす。**
  let mutable enabled = false

  /// 作った物 -> 元の物。**同じ物のときは呼ばない**（vanish は singleton
  /// なので、作り直しても同じ物が返る。自己対になって表が太るだけ）。
  ///
  /// 鎖は 2 段 になりうる —— 展開したものは param を差し込んだものから
  /// 作られる（`refAction` → `substActionElm` → `expandActionElm`）。
  /// **受け取る側が閉包を取る。**
  let mutable pair : obj -> obj -> unit = fun _ _ -> ()
